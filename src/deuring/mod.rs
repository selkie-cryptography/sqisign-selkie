/// A kernel generator decomposed in a torsion basis (P, Q).
///
/// Represents the point [a]P + [b]Q where a, b are scalars. The
/// actual curve point is computed by evaluating the scalars against
/// a specific torsion basis.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct KernelDecomposition {
    /// Coefficient of P.
    pub a: Scalar,
    /// Coefficient of Q.
    pub b: Scalar,
}

/// Extension trait for computing endomorphism action matrices
/// from quaternion elements already expressed in the order basis.
///
/// Given an element with coordinates (c₀, c₁, c₂, c₃) in the order
/// basis, computes M_α = c₀·M₁ + c₁·M₂ + c₂·M₃ + c₃·M₄ (mod 2^f).
///
/// See §3.2.1.1 of the spec.
pub trait DeuringAction {
    /// Compute the action matrix given four order-basis action matrices.
    ///
    /// The element's (a, b, c, d) coordinates are used as coefficients.
    /// The caller must ensure the element is expressed in the order basis,
    /// not the {1, i, j, k} basis.
    fn action_matrix(&self, basis_matrices: &[ActionMatrix; 4], f: TorsionExponent)
    -> ActionMatrix;
}

impl DeuringAction for Element {
    fn action_matrix(
        &self,
        basis_matrices: &[ActionMatrix; 4],
        f: TorsionExponent,
    ) -> ActionMatrix {
        let coords = [
            *self.a.as_bigint(),
            *self.b.as_bigint(),
            *self.c.as_bigint(),
            *self.d.as_bigint(),
        ];
        let mut result = ActionMatrix::ZERO;
        for i in 0..4 {
            result = result.add_scaled_mod(&coords[i], &basis_matrices[i], f.value());
        }
        result
    }
}

/// Extension trait for converting an ideal to a kernel generator
/// via the Deuring correspondence.
///
/// See [Algorithm 3.14] from the spec.
///
/// [Algorithm 3.14]: https://sqisign.org/spec/sqisign-20250707.pdf#algorithm.3.14
pub trait IdealKernel {
    /// Compute the kernel decomposition for this ideal of norm 2^e.
    ///
    /// Returns scalars (a, b) such that ker φ_I is generated by
    /// [a·2^{f-e}]P₀ + [b·2^{f-e}]Q₀, where (P₀, Q₀) is the
    /// precomputed torsion basis of E₀[2^f].
    fn to_kernel(
        &self,
        basis_matrices: &[ActionMatrix; 4],
        e: TorsionExponent,
    ) -> Option<KernelDecomposition>;
}

impl IdealKernel for LeftIdeal<4> {
    fn to_kernel(
        &self,
        basis_matrices: &[ActionMatrix; 4],
        e: TorsionExponent,
    ) -> Option<KernelDecomposition> {
        // Step 1: Find α ∈ O₀ such that I = O₀⟨α, 2^e⟩.
        let alpha = self.generator()?;

        // Step 2: Compute M_α mod 2^e.
        let m_alpha = alpha.action_matrix(basis_matrices, e);

        // Step 3: Find [a, b]^T in the right kernel of M_α mod 2^e.
        // For a 2×2 matrix, the kernel is spanned by (-m01, m00)^T.
        let modulus = BigInt::<4>::ONE.shl(e.value());

        // Try first row: kernel direction = (-m01, m00).
        let a_big = BigInt::<4>::from(*m_alpha.entry(0, 1))
            .wrapping_neg()
            .ct_mod(&modulus);
        let b_big = BigInt::<4>::from(*m_alpha.entry(0, 0)).ct_mod(&modulus);

        let (check0, check1) = m_alpha.eval_mod(&a_big, &b_big, e.value());
        if bool::from(check0.is_zero()) && bool::from(check1.is_zero()) {
            return Some(KernelDecomposition {
                a: Scalar::from(a_big),
                b: Scalar::from(b_big),
            });
        }

        // If first row was zero, try second row.
        let a_big = BigInt::<4>::from(*m_alpha.entry(1, 1))
            .wrapping_neg()
            .ct_mod(&modulus);
        let b_big = BigInt::<4>::from(*m_alpha.entry(1, 0)).ct_mod(&modulus);

        let (check0, check1) = m_alpha.eval_mod(&a_big, &b_big, e.value());
        if bool::from(check0.is_zero()) && bool::from(check1.is_zero()) {
            return Some(KernelDecomposition {
                a: Scalar::from(a_big),
                b: Scalar::from(b_big),
            });
        }

        None
    }
}

