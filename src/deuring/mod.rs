/// Compute the even (non-backtracking) response isogeny.
///
/// Given curve E_chl with torsion basis (P, Q), quaternion α,
/// and integers e' (= e'_rsp) and r (= r_rsp), computes the
/// even response isogeny φ^even_rsp : E_chl → E.
///
/// Returns the codomain curve E and the images P', Q' of the
/// basis points.
///
/// Implements [ComputeEvenNonBacktrackingResponse][Alg. 4.6].
///
/// [Alg. 4.6]: https://sqisign.org/spec/sqisign-20250707.pdf#algorithm.4.6
pub fn compute_even_response(
    _curve: &Curve,
    P: &ProjectiveXOnlyPoint,
    Q: &ProjectiveXOnlyPoint,
    alpha: &Element,
    e_prime: TorsionExponent,
    r_rsp: TorsionExponent,
) -> Option<(Curve, ProjectiveXOnlyPoint, ProjectiveXOnlyPoint)> {
    let e_prime = e_prime.value();
    let r_rsp = r_rsp.value();

    // Step 1: I = O₀·α + O₀·(2^r)
    let norm = BigInt::<4>::ONE.shl(r_rsp);
    let ideal = LeftIdeal::new(alpha, &norm, EXTREMAL_ORDERS[0].order());

    // Step 2: (s, t) ← IdealToKernel(I)
    let basis_mats = [
        ACTION_MATRICES[0][3], // gen2
        ACTION_MATRICES[0][4], // gen3
        ACTION_MATRICES[0][5], // gen4
        ACTION_MATRICES[0][0], // i (for the kernel computation)
    ];
    let decomp = ideal.to_kernel(&basis_mats, TorsionExponent::try_from(r_rsp).ok()?)?;

    // Step 3: K = [2^(e'+2) · s]P + [2^(e'+2) · t]Q
    let shift = e_prime + 2;
    let s_shifted = Scalar::from_limbs(*decomp.a.as_limbs()).mul_mod2k(
        &Scalar::from_limbs(*BigInt::<4>::ONE.shl(shift).as_limbs()),
        256,
    );
    let t_shifted = Scalar::from_limbs(*decomp.b.as_limbs()).mul_mod2k(
        &Scalar::from_limbs(*BigInt::<4>::ONE.shl(shift).as_limbs()),
        256,
    );

    // Compute K = [s_shifted]P + [t_shifted]Q using the biladder.
    // Need PmQ for the three-point ladder.
    let PmQ = P.projective_difference(Q);
    let basis = TorsionBasis::new(*P, *Q, PmQ);
    // TODO: PmQ from projective_difference may pick wrong branch.
    // In signing, the basis (P, Q, P-Q) should have been propagated
    // from a prior computation, not recomputed here.
    let K = basis.biscalar_mul(
        &s_shifted,
        &t_shifted,
        TorsionExponent::try_from(r_rsp + shift).ok()?,
    );

    // Step 4: E', {P', Q'} ← TwoisogenyChainSmall(K, E, r, {P, Q}, true)
    let (new_curve, images) = CurveKernel::new(K)
        .isogeny_small(TorsionExponent::try_from(r_rsp).ok()?, &[*P, *Q], true)
        .ok()?;

    Some((new_curve, images[0], images[1]))
}

