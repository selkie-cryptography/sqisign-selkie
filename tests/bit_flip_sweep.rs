//! Exhaustive single-bit-flip sweep on a valid signature.
//!
//! Every one of the `8 * SIGNATURE_BYTES = 1184` single-bit
//! perturbations of a canonical KAT signature must be rejected (at
//! parse or at verify time) and must never panic, with the documented
//! exception of [`KAT_INHERENT_MALLEABLE_BITS`] (see below). A bit
//! position outside that allowlist that still verifies is signature
//! malleability the spec doesn't permit — the bit didn't contribute
//! to integrity, so an attacker who intercepts a message could rewrite
//! that bit and the recipient wouldn't notice.
//!
//! Sister test to [`malleability`](../malleability/index.html) — that
//! one mutates *typed components* (swap `n_bt` / `r_rsp`, replace
//! `curve_aux`, etc.), this one is the blind exhaustive sweep.
//!
//! Two granularities ship in this file:
//!
//! - [`bit_flip_sweep_kat0_rejects_all_perturbations`] runs only on KAT 0 and
//!   stays in the default `cargo test` / nextest suite (~3 min). It guards the
//!   minimal residual set.
//! - [`bit_flip_sweep_all_kats_matches_residuals`] is `#[ignore]` and sweeps
//!   every one of the 100 NIST-I KAT signatures (~25 min), asserting each
//!   signature's residual matches the pinned table below. Run via the `kat`
//!   nextest profile or `cargo test bit_flip_sweep_all_kats -- --ignored
//!   --nocapture`.
//!
//! # Inherent malleability
//!
//! Verify's `M_chl` application multiplies the scaled `E_chl`-basis by
//! a 4-entry scalar matrix and pushes the result through a chain of
//! 2-isogenies (the small even-response chain plus the outer (2,2)-
//! chain). Each isogeny step has a kernel of order 2 generated by
//! some 2-torsion point on its domain curve. Flipping the high bits of
//! an `M_chl` scalar shifts the corresponding output basis point by a
//! multiple of that 2-torsion generator — which the chain absorbs,
//! leaving the codomain curve and final hash unchanged.
//!
//! The residual size therefore grows roughly with `r_rsp` (more chain
//! steps absorb more bits), and the bit positions are always near the
//! top of one of the four `M_chl` entries (bits 528..1040 of the sig,
//! grouped into 4 × 128-bit scalars, top bit at position
//! `127 − n_bt` of each entry). Per-signature structural alignment
//! makes the exact count vary inside a class: e.g., `(n_bt = 0,
//! r_rsp = 1)` KATs land anywhere from 6 to 9 bits.
//!
//! These are not spec violations: the spec's `M_chl` entry bound
//! ([§4.5][§4.5] Alg. 4.9 step 5, enforced at parse by
//! `ChallengeMatrix::parse`) is `2^(e_rsp − n_bt + 2)` — the full
//! encoding range. The malleability is intrinsic to the matrix-then-
//! isogeny structure; tightening the byte encoding to remove it would
//! go beyond the spec. SQIsign as specified satisfies EUF-CMA but not
//! SUF-CMA.
//!
//! The residual table is pinned so a future change that adds or
//! removes a malleable bit fails loudly — either direction is
//! noteworthy.
//!
//! [§4.5]: https://sqisign.org/spec/sqisign-20250707.pdf#section.4.5

