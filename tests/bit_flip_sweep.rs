fn sweep_kat(idx: usize) -> Vec<usize> {
    let (_seed, pk_hex, _sk, msg_hex, sig_hex) = KAT_VECTORS[idx];
    let pk_bytes = hex::decode(pk_hex).expect("pk hex");
    let sig = hex::decode(sig_hex).expect("sig hex");
    let msg = hex::decode(msg_hex).expect("msg hex");

    let pk_arr: &[u8; VERIFYING_KEY_BYTES] = pk_bytes.as_slice().try_into().expect("pk length");
    let vk = VerifyingKey::from_bytes(pk_arr).expect("baseline pk parses");

    let sig_arr: [u8; SIGNATURE_BYTES] = sig[..SIGNATURE_BYTES]
        .try_into()
        .expect("sig prefix present");
    let baseline_sig = Signature::from_bytes(&sig_arr).expect("baseline sig parses");
    vk.verify(&msg, &baseline_sig)
        .expect("baseline (vk, sig, msg) must verify");

    let mut accepted: Vec<usize> = Vec::new();
    for bit in 0..(SIGNATURE_BYTES * 8) {
        let mut flipped = sig_arr;
        flipped[bit / 8] ^= 1u8 << (bit % 8);
        if let Ok(s) = Signature::from_bytes(&flipped) {
            if vk.verify(&msg, &s).is_ok() {
                accepted.push(bit);
            }
        }
    }
    accepted
}

fn assert_residual_matches(idx: usize) {
    let actual = sweep_kat(idx);
    let expected = KAT_INHERENT_MALLEABLE_BITS[idx];
    let unexpected: Vec<usize> = actual
        .iter()
        .copied()
        .filter(|b| !expected.contains(b))
        .collect();
    assert!(
        unexpected.is_empty(),
        "KAT {idx}: {} unexpected single-bit sig flips still verified — \
         outside the pinned residual; investigate whether a fix added \
         malleability, bits {unexpected:?}",
        unexpected.len(),
    );
    let missing: Vec<usize> = expected
        .iter()
        .copied()
        .filter(|b| !actual.contains(b))
        .collect();
    assert!(
        missing.is_empty(),
        "KAT {idx}: previously-documented malleable bits now reject — \
         the residual has shrunk; investigate whether a fix tightened \
         the math (and shrink the pinned set), bits {missing:?}",
    );
}

/// Default-suite sweep on KAT 0. Asserts the residual matches
/// [`KAT_INHERENT_MALLEABLE_BITS[0]`].
#[test]
fn bit_flip_sweep_kat0_rejects_all_perturbations() {
    assert_residual_matches(0);
}

