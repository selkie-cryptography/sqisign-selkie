#![no_main]
//! Structure-aware verify fuzz target.
//!
//! Anchors the verifying key and the `curve_aux` Fp2 region of the
//! signature to KAT 0's bytes (both known to parse), then XORs
//! libFuzzer's input over the remaining sig bytes — `n_bt`, `r_rsp`,
//! `M_chl`, `chl`, both hint bytes — plus an optional trailing
//! message. Every iteration that supplies enough bytes therefore
//! reaches `VerifyingKey::verify`, where the actual (2,2)-chain runs,
//! rather than bouncing at `from_bytes` like the raw-bytes `fuzz_verify`
//! target does for ~99.999% of random inputs.
//!
//! Pair with `fuzz_verify` (raw bytes) for breadth and this target
//! for depth on the verify code path.

use libfuzzer_sys::fuzz_target;
use sqisign_selkie::{SIGNATURE_BYTES, Signature, VERIFYING_KEY_BYTES, VerifyingKey};

/// KAT 0 verifying key bytes. Always parses; supersingular.
const KAT0_PK: [u8; VERIFYING_KEY_BYTES] = [
    0x07, 0xCC, 0xD2, 0x14, 0x25, 0x13, 0x6F, 0x6E, 0x86, 0x5E, 0x49, 0x7D, 0x2D, 0x4D, 0x20, 0x8F,
    0x00, 0x54, 0xAD, 0x81, 0x37, 0x20, 0x66, 0xE8, 0x17, 0x48, 0x07, 0x87, 0xAA, 0xF7, 0xB2, 0x02,
    0x95, 0x50, 0xC8, 0x9E, 0x89, 0x2D, 0x61, 0x8C, 0xE3, 0x23, 0x0F, 0x23, 0x51, 0x0B, 0xFB, 0xE6,
    0x8F, 0xCC, 0xDD, 0xAE, 0xA5, 0x1D, 0xB1, 0x43, 0x6B, 0x46, 0x2A, 0xDF, 0xAF, 0x00, 0x8A, 0x01,
    0x0B,
];

/// KAT 0 signature baseline. The structure-aware mutation anchors
/// bytes 0..64 (curve_aux) to these values and XORs libFuzzer's
/// input onto bytes 64.. so that:
///   * curve_aux always parses (KAT 0 supersingular E_aux),
///   * n_bt, r_rsp, M_chl, chl, hints get random bit flips,
///   * a zero input recovers the valid KAT 0 signature unchanged.
const KAT0_SIG: [u8; SIGNATURE_BYTES] = [
    0x84, 0x22, 0x86, 0x51, 0xF2, 0x71, 0xB0, 0xF3, 0x9F, 0x2F, 0x19, 0xF2, 0xE8, 0x71, 0x8F, 0x31,
    0xED, 0x33, 0x65, 0xAC, 0x9E, 0x5C, 0xB3, 0x03, 0xAF, 0xE6, 0x63, 0xD0, 0xCF, 0xC1, 0x1F, 0x04,
    0x55, 0xD8, 0x91, 0xB0, 0xCA, 0x6C, 0x7E, 0x65, 0x3F, 0x9B, 0xA2, 0x66, 0x77, 0x30, 0xBB, 0x77,
    0xBE, 0xFE, 0x1B, 0x1A, 0x31, 0x82, 0x84, 0x04, 0x28, 0x4A, 0xF8, 0xFD, 0x7B, 0xAA, 0xCC, 0x01,
    0x00, 0x01, 0xD9, 0x74, 0xB5, 0xCA, 0x67, 0x1F, 0xF6, 0x57, 0x08, 0xD8, 0xB4, 0x62, 0xA5, 0xA8,
    0x4A, 0x14, 0x43, 0xEE, 0x9B, 0x5F, 0xED, 0x72, 0x18, 0x76, 0x7C, 0x9D, 0x85, 0xCE, 0xED, 0x04,
    0xDB, 0x0A, 0x69, 0xA2, 0xF6, 0xEC, 0x3B, 0xE8, 0x35, 0xB3, 0xB2, 0x62, 0x4B, 0x9A, 0x0D, 0xF6,
    0x88, 0x37, 0xAD, 0x00, 0xBC, 0xAC, 0xC2, 0x7D, 0x1E, 0xC8, 0x06, 0xA4, 0x48, 0x40, 0x26, 0x74,
    0x71, 0xD8, 0x6E, 0xFF, 0x34, 0x47, 0x01, 0x8A, 0xDB, 0x0A, 0x65, 0x51, 0xEE, 0x83, 0x22, 0xAB,
    0x30, 0x01, 0x02, 0x02,
];

/// Bytes 0..64 of the signature encode `curve_aux` (an `Fp2`).
/// Keeping them unchanged guarantees `Signature::from_bytes` sees a
/// well-formed supersingular `E_aux` and progresses past the
/// curve-validity rejection paths.
const CURVE_AUX_LEN: usize = 64;

fuzz_target!(|data: &[u8]| {
    let Ok(vk) = VerifyingKey::from_bytes(&KAT0_PK) else {
        return;
    };

    if data.len() < SIGNATURE_BYTES - CURVE_AUX_LEN {
        return;
    }

    let mut sig_bytes = KAT0_SIG;
    for (i, b) in data[..SIGNATURE_BYTES - CURVE_AUX_LEN].iter().enumerate() {
        sig_bytes[CURVE_AUX_LEN + i] ^= *b;
    }
    let msg = &data[SIGNATURE_BYTES - CURVE_AUX_LEN..];

    let Ok(sig) = Signature::from_bytes(&sig_bytes) else {
        return;
    };

    // Verify must not panic on any input. Reject-as-Err is the
    // expected outcome on almost every mutation; an actual `Ok` is a
    // forgery and would be a hard test failure if libfuzzer's
    // assertions could catch that — for now, panics are the signal.
    let _ = vk.verify(msg, &sig);
});
